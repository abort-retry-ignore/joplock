'use strict';

// Joplock is AGPL-3.0-or-later. The license text must be the real one, the metadata must agree,
// the running app must point users at the source (AGPL section 13: a network service must offer
// its source to the people using it), and every third-party file we ship must be accounted for in
// THIRD_PARTY_NOTICES.md (minified bundles lose their license banners, MIT/BSD require the notice).

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8');

test('LICENSE is the full, unmodified GNU AGPL v3 text', () => {
	const text = read('LICENSE');
	const lines = text.split('\n');
	assert.equal(lines[0].trim(), 'GNU AFFERO GENERAL PUBLIC LICENSE');
	assert.equal(lines[1].trim(), 'Version 3, 19 November 2007');
	assert.ok(lines.length >= 660 && lines.length <= 663, `unexpected length: ${lines.length} lines`);
	assert.match(text, /13\. Remote Network Interaction; Use with the GNU General Public License\./);
	assert.match(text, /END OF TERMS AND CONDITIONS/);
	assert.match(text.trimEnd(), /<https:\/\/www\.gnu\.org\/licenses\/>\.$/);
});

test('package metadata declares the same license', () => {
	assert.equal(JSON.parse(read('package.json')).license, 'AGPL-3.0-or-later');
	assert.equal(JSON.parse(read('package-lock.json')).packages[''].license, 'AGPL-3.0-or-later');
});

test('the README states the license and points at the notices', () => {
	const readme = read('README.md');
	assert.match(readme, /## License/);
	assert.match(readme, /GNU Affero General Public License/);
	assert.match(readme, /THIRD_PARTY_NOTICES\.md/);
});

test('the Docker image carries the license texts', () => {
	assert.match(read('Dockerfile'), /^COPY LICENSE THIRD_PARTY_NOTICES\.md \.\/$/m);
});

test('the running app tells users the license and where the source is (AGPL section 13)', () => {
	const templates = require('../app/templates');
	const html = templates.settingsPage({ user: { id: 'u', email: 'a@b.c' }, settings: {}, activeTab: 'about' });
	assert.match(html, /<span class="about-label">License<\/span>/);
	assert.match(html, /href="https:\/\/www\.gnu\.org\/licenses\/agpl-3\.0\.html"/);
	assert.match(html, /href="https:\/\/github\.com\/abort-retry-ignore\/joplock"[^>]*>source code<\/a>/);
});

// Joplock's own files in public/; everything else there is third-party and must be in the notices.
const FIRST_PARTY = new Set(['app.js', 'cm-extras.js', 'viewport.js', 'service-worker.js', 'styles.css', 'offline.html', 'manifest.webmanifest', 'icon.svg', 'reference.docx']);

test('every third-party file shipped in public/ is listed in THIRD_PARTY_NOTICES.md', () => {
	const notices = read('THIRD_PARTY_NOTICES.md');
	const shipped = [];
	for (const name of fs.readdirSync(path.join(root, 'public'))) {
		const full = path.join(root, 'public', name);
		if (fs.statSync(full).isDirectory()) {
			if (name === 'fonts') for (const f of fs.readdirSync(full)) shipped.push(`public/fonts/${f}`);
			else if (name === 'tinymce') shipped.push('public/tinymce/');
			continue; // apple-splash: generated by scripts/generatePwaAssets.mjs
		}
		if (/\.png$/.test(name) || FIRST_PARTY.has(name)) continue; // generated icons, our own code
		shipped.push(`public/${name}`);
	}
	assert.ok(shipped.length >= 8, `expected the vendored bundles, found ${shipped.length}`);
	const unlisted = shipped.filter(p => !notices.includes(p) && !(p.startsWith('public/fonts/') && notices.includes('public/fonts/CascadiaMono-*.woff2')));
	assert.deepEqual(unlisted, [], 'add these to THIRD_PARTY_NOTICES.md (with an AGPL-compatible license), or to FIRST_PARTY if they are ours');
});

test('no runtime dependency carries a license that is incompatible with the AGPL', () => {
	const ok = /^(MIT|ISC|0BSD|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|SEE LICENSE IN license\.md)$/;
	const deps = Object.keys(JSON.parse(read('package.json')).dependencies || {});
	const bad = [];
	for (const dep of deps) {
		const manifest = path.join(root, 'node_modules', dep, 'package.json');
		if (!fs.existsSync(manifest)) continue; // not installed in this checkout
		const license = JSON.parse(fs.readFileSync(manifest, 'utf8')).license || '';
		if (!ok.test(license)) bad.push(`${dep}: ${license || '(none)'}`);
	}
	assert.deepEqual(bad, []);
	// the one non-permissive dependency is TinyMCE, and it must stay "or later"
	const tiny = path.join(root, 'node_modules', 'tinymce', 'license.md');
	if (fs.existsSync(tiny)) assert.match(fs.readFileSync(tiny, 'utf8'), /GNU General Public License Version 2 or later/);
});
